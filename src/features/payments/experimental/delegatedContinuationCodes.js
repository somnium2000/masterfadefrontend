const CONTINUATION_ERRORS = new Set([
  'PIXELPAY_3DS_COLLECTION_URL_ABSENT',
  'PIXELPAY_3DS_COLLECTION_URL_NULL',
  'PIXELPAY_3DS_COLLECTION_URL_EMPTY',
  'PIXELPAY_3DS_COLLECTION_URL_INVALID',
  'PIXELPAY_3DS_CONTINUATION_INVALID',
]);

export const isDelegatedContinuationError = code => CONTINUATION_ERRORS.has(code);
